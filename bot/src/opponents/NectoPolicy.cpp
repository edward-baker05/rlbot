struct NectoPolicy::Module {
	torch::jit::script::Module mod;
	torch::Device device = torch::kCPU;
};

NectoPolicy::NectoPolicy(const std::filesystem::path &modelPath, float beta,
						 int64_t seed, bool useGPU)
	: beta(std::clamp(beta, 0.f, 1.f)),
	  rng(seed < 0 ? std::random_device{}() : static_cast<uint32_t>(seed)) {
	if (!std::filesystem::is_regular_file(modelPath))
		throw std::runtime_error("NectoPolicy: no model file at " +
								 modelPath.string());

	// The device is the caller's call, and during training it should be the GPU.
	//
	// This was originally CPU-only, on the reasoning that training owns the GPU
	// and ~3ms for a batch of ~50 is nothing. That was wrong about where the
	// 3ms lands: this forward runs from preStepFn, which the learner calls
	// AFTER envSet->Sync() and BEFORE StepSecondHalf -- serial on the collection
	// thread, with all twelve arena workers parked. So it is 3ms added to every
	// env step, not 3ms hidden in the noise. Measured against the same GPU
	// sitting at ~11% utilisation for the whole collection phase.
	//
	// Note this still does NOT call at::set_num_threads(), which matters for the
	// CPU fallback below. Necto's own agent.py does, because under RLBot it must
	// not steal the game's CPU -- but that setting is process-global in libtorch,
	// so calling it here throttled PPO's own inference and update to a single
	// thread. Measured cost of getting this wrong: collection throughput roughly
	// halved.
	onGPU = useGPU && torch::cuda::is_available();

	module = std::make_unique<Module>();
	module->device = onGPU ? torch::Device(torch::kCUDA) : torch::Device(torch::kCPU);
	try {
		module->mod = torch::jit::load(modelPath.string(), module->device);
		module->mod.eval();
		family = DetectFamily(module->mod);
		// Only on the GPU, and only ever a no-op on Necto. See the function.
		if (onGPU)
			RetargetDeviceConstants(module->mod, module->device);
	} catch (const std::exception &e) {
		throw std::runtime_error("NectoPolicy: failed to load " +
								 modelPath.string() + ": " + e.what());
	}

	if (family == NectoFamily::Nexto)
		lookupTable = NextoLookupTable();

	// agent.py: logits *= log((beta + 1) / (1 - beta), 3). Falls out to exactly
	// 1.0 at beta = 0.5, which is why that value is plain on-policy sampling.
	logitScale = (this->beta >= 1.f || this->beta <= 0.f)
					 ? 0.f
					 : std::log((this->beta + 1.f) / (1.f - this->beta)) /
						   std::log(3.f);
}

NectoPolicy::~NectoPolicy() = default;

std::vector<Action> NectoPolicy::NextoLookupTable() {
	return BuildNextoLookupTable();
}

int NectoPolicy::TokenCount(const GameState &state) {
	return 1 + static_cast<int>(state.players.size()) +
		   CommonValues::BOOST_LOCATIONS_AMOUNT;
}

void NectoPolicy::BuildObs(NectoFamily family, const GameState &gs,
						   int playerIdx, const Action &prevAction, float *qOut,
						   float *kvOut) {
	const bool nexto = family == NectoFamily::Nexto;
	const int numPlayers = static_cast<int>(gs.players.size());
	const int n = TokenCount(gs);

	if (playerIdx < 0 || playerIdx >= numPlayers)
		throw std::runtime_error("NectoPolicy::BuildObs: player index out of range");
	if (static_cast<int>(gs.boostPadTimers.size()) <
		CommonValues::BOOST_LOCATIONS_AMOUNT)
		throw std::runtime_error("NectoPolicy::BuildObs: game state has no boost pad data");
	if (nexto && static_cast<int>(gs.boostPads.size()) <
					 CommonValues::BOOST_LOCATIONS_AMOUNT)
		throw std::runtime_error("NectoPolicy::BuildObs: game state has no boost pad states");

	std::fill(kvOut, kvOut + static_cast<size_t>(n) * FEATURES, 0.f);

	// Token order. Necto is (ball, cars, pads); Nexto is (cars, ball, pads).
	// Nothing in the model can tell the difference -- EARLPerceiver has no
	// positional encoding, so kv is a set -- but matching each builder exactly
	// keeps the self-test a straight elementwise diff.
	const int ballRow = nexto ? numPlayers : 0;
	const int carRow0 = nexto ? 0 : 1;
	const int padRow0 = 1 + numPlayers;

	auto row = [&](int i) { return kvOut + static_cast<size_t>(i) * FEATURES; };
	auto setVec = [](float *r, int col, const Vec &v) {
		r[col] = v.x;
		r[col + 1] = v.y;
		r[col + 2] = v.z;
	};

	{ // Ball. Leaves the forward/up columns zero, as both builders do.
		float *r = row(ballRow);
		r[3] = 1.f; // is_ball
		setVec(r, COL_POS, gs.ball.pos);
		setVec(r, COL_LIN_VEL, gs.ball.vel);
		setVec(r, COL_ANG_VEL, gs.ball.angVel);
	}

	// Cars. Team flags are ABSOLUTE here (blue -> col 1, orange -> col 2); the
	// swap for an orange main car happens below, in the Python's order. Do not
	// shortcut this by computing the flags relative to the main car -- the
	// inversion below would then apply on top of an already-relative encoding.
	for (int i = 0; i < numPlayers; i++) {
		const Player &p = gs.players[i];
		float *r = row(carRow0 + i);
		r[p.team == Team::BLUE ? 1 : 2] = 1.f;
		setVec(r, COL_POS, p.pos);
		setVec(r, COL_LIN_VEL, p.vel);
		setVec(r, COL_FORWARD, p.rotMat.forward);
		setVec(r, 14, p.rotMat.up);
		setVec(r, COL_ANG_VEL, p.angVel);
		r[20] = p.boost / 100.f; // CarState::boost is 0-100, both want 0-1
		// Necto: the sim's real respawn timer. necto_obs.py re-seeds this to 3
		// whenever it reaches 0, which is an artifact of its RLBot port -- the
		// model was trained on the real thing.
		//
		// Nexto: the raw is_demoed flag. Its builder reads encoded_player[33],
		// which is exactly that bool, and the same function ran at training
		// time, so a timer here would be the wrong scale AND the wrong quantity.
		r[COL_TIMER] = nexto ? (p.isDemoed ? 1.f : 0.f)
							 : p.demoRespawnTimer / 10.f;
		r[22] = p.isOnGround ? 1.f : 0.f;
		r[23] = p.HasFlipOrJump() ? 1.f : 0.f;
	}

	// Boost pads. Ordering within the pad block does not matter -- the model
	// attends over the token set and each pad carries its own position -- so
	// long as position, size and timer for a row all come from the same pad.
	for (int i = 0; i < CommonValues::BOOST_LOCATIONS_AMOUNT; i++) {
		const Vec &loc = CommonValues::BOOST_LOCATIONS[i];
		float *r = row(padRow0 + i);
		r[4] = 1.f; // is_boost
		setVec(r, COL_POS, loc);
		r[20] = 0.12f + 0.88f * (loc.z > 72.f ? 1.f : 0.f); // big pads sit at z=73
		// Necto reads the true remaining cooldown; Nexto's builder puts the raw
		// availability bit here instead (its own `# FIXME boost timer`). Index
		// directly either way: GameState::GetBoostPadTimers() has its `inverted`
		// flag swapped upstream.
		r[COL_TIMER] = nexto ? (gs.boostPads[i] ? 1.f : 0.f)
							 : gs.boostPadTimers[i] / 10.f;
	}

	for (int i = 0; i < n; i++) {
		float *r = row(i);
		for (int c = 0; c < FEATURES; c++)
			r[c] /= NORM[c];
	}

	const int mainRow = carRow0 + playerIdx;
	row(mainRow)[0] = 1.f; // is_main / is_self

	// Orange plays the mirrored field.
	if (gs.players[playerIdx].team == Team::ORANGE) {
		for (int i = 0; i < n; i++) {
			float *r = row(i);
			std::swap(r[1], r[2]);
			for (int c = 0; c < FEATURES; c++)
				r[c] *= INVERT[c];
		}
	}

	// q keeps ABSOLUTE position and velocity, and must be taken before kv is
	// made relative below.
	std::copy(row(mainRow), row(mainRow) + FEATURES, qOut);
	for (int k = 0; k < static_cast<int>(Action::ELEM_AMOUNT); k++)
		qOut[FEATURES + k] = prevAction[k];

	if (!nexto) {
		// Necto: kv positions AND linear velocities become relative to the main
		// car. Nothing is rotated -- the frame stays axis-aligned to the field.
		for (int i = 0; i < n; i++) {
			float *r = row(i);
			for (int c = COL_POS; c < COL_FORWARD; c++)
				r[c] -= qOut[c];
		}
		return;
	}

	// Nexto: position only, and then every x/y pair is rotated into the main
	// car's yaw frame -- `NextoObsBuilder.convert_to_relative`. Velocity is NOT
	// subtracted; the commented-out line doing that is still in the upstream
	// source directly above the one that replaced it.
	for (int i = 0; i < n; i++) {
		float *r = row(i);
		for (int c = COL_POS; c < COL_LIN_VEL; c++)
			r[c] -= qOut[c];
	}

	// theta comes from the main car's forward, already inverted for orange, and
	// is atan2(x, y) rather than the usual atan2(y, x) -- so the rotation below
	// carries the car's nose onto +y, not +x.
	const float theta = std::atan2(qOut[COL_FORWARD], qOut[COL_FORWARD + 1]);
	const float ct = std::cos(theta);
	const float st = std::sin(theta);

	// Columns 5..19 by stride 3: position, linear velocity, forward, up and
	// angular velocity all get the same yaw rotation. q itself is left alone,
	// which is what makes it the frame everything else is expressed in.
	for (int i = 0; i < n; i++) {
		float *r = row(i);
		for (int c = COL_POS; c < COL_ANG_VEL + 3; c += 3) {
			const float x = r[c];
			const float y = r[c + 1];
			r[c] = ct * x - st * y;
			r[c + 1] = st * x + ct * y;
		}
	}
}

Action NectoPolicy::SampleAction(const float *const *heads,
								 const int *headSizes) {
	int picked[NUM_HEADS] = {};

	for (int h = 0; h < NUM_HEADS; h++) {
		const int k = headSizes[h];
		const float *logits = heads[h];

		if (beta >= 1.f) { // argmax
			int best = 0;
			for (int c = 1; c < k; c++)
				if (logits[c] > logits[best])
					best = c;
			picked[h] = best;
			continue;
		}

		if (beta <= 0.f) { // uniform
			picked[h] = std::uniform_int_distribution<int>(0, k - 1)(rng);
			continue;
		}

		float scaled[MAX_HEAD_SIZE];
		float maxLogit = -std::numeric_limits<float>::infinity();
		for (int c = 0; c < k; c++) {
			scaled[c] = logits[c] * logitScale;
			maxLogit = std::max(maxLogit, scaled[c]);
		}

		float sum = 0.f;
		for (int c = 0; c < k; c++) {
			scaled[c] = std::exp(scaled[c] - maxLogit);
			sum += scaled[c];
		}

		const float u =
			std::uniform_real_distribution<float>(0.f, 1.f)(rng) * sum;
		float acc = 0.f;
		picked[h] = k - 1;
		for (int c = 0; c < k; c++) {
			acc += scaled[c];
			if (u <= acc) {
				picked[h] = c;
				break;
			}
		}
	}

	// agent.py's mapping. Heads 0 and 1 are ternary and shift to {-1, 0, 1};
	// the rest are binary. Note pitch reuses head 0 and yaw/roll split head 1
	// on the handbrake bit -- that is why Necto's action space does not line up
	// with RLGymCPP's 90-entry lookup table.
	const float throttle = static_cast<float>(picked[0] - 1);
	const float steer = static_cast<float>(picked[1] - 1);
	const float jump = static_cast<float>(picked[2]);
	const float boost = static_cast<float>(picked[3]);
	const float handbrake = static_cast<float>(picked[4]);

	Action act = {};
	act.throttle = throttle;
	act.steer = steer;
	act.pitch = throttle;
	act.yaw = steer * (1.f - handbrake);
	act.roll = steer * handbrake;
	act.jump = jump;
	act.boost = boost;
	act.handbrake = handbrake;
	return act;
}

Action NectoPolicy::SampleLookupAction(const float *logits, int count) {
	// Same temperature semantics as SampleAction, over one wide head instead of
	// five narrow ones. nexto/agent.py runs a single Categorical here, and at
	// beta = 0 zeroes the finite logits, which is a uniform draw over all of
	// them -- every entry is finite, since nothing is padded at this width.
	int picked = 0;

	if (beta >= 1.f) { // argmax
		for (int c = 1; c < count; c++)
			if (logits[c] > logits[picked])
				picked = c;
	} else if (beta <= 0.f) { // uniform
		picked = std::uniform_int_distribution<int>(0, count - 1)(rng);
	} else {
		logitBuf.resize(count);

		float maxLogit = -std::numeric_limits<float>::infinity();
		for (int c = 0; c < count; c++) {
			logitBuf[c] = logits[c] * logitScale;
			maxLogit = std::max(maxLogit, logitBuf[c]);
		}

		float sum = 0.f;
		for (int c = 0; c < count; c++) {
			logitBuf[c] = std::exp(logitBuf[c] - maxLogit);
			sum += logitBuf[c];
		}

		const float u =
			std::uniform_real_distribution<float>(0.f, 1.f)(rng) * sum;
		float acc = 0.f;
		picked = count - 1;
		for (int c = 0; c < count; c++) {
			acc += logitBuf[c];
			if (u <= acc) {
				picked = c;
				break;
			}
		}
	}

	return lookupTable[picked];
}

void NectoPolicy::InferBatch(const std::vector<NectoRequest> &requests,
							 std::vector<Action> &outActions) {
	outActions.assign(requests.size(), Action{});
	if (requests.empty())
		return;

	// Group by token count so every batch is exact. Padding ragged batches is
	// close but not exact -- the traced model's mask is not fully wired, so
	// padded rows still perturb the logits by ~0.03. At 1v1 this is one group.
	std::map<int, std::vector<int>> byTokens;
	for (int i = 0; i < static_cast<int>(requests.size()); i++)
		byTokens[TokenCount(*requests[i].state)].push_back(i);

	for (const auto &[n, idxs] : byTokens) {
		const int b = static_cast<int>(idxs.size());

		qBuf.assign(static_cast<size_t>(b) * Q_SIZE, 0.f);
		kvBuf.assign(static_cast<size_t>(b) * n * FEATURES, 0.f);
		maskBuf.assign(static_cast<size_t>(b) * n, 0.f);

		for (int j = 0; j < b; j++) {
			const NectoRequest &req = requests[idxs[j]];
			BuildObs(family, *req.state, req.playerIdx, req.prevAction,
					 qBuf.data() + static_cast<size_t>(j) * Q_SIZE,
					 kvBuf.data() + static_cast<size_t>(j) * n * FEATURES);
		}

		c10::IValue out;
		{
			torch::NoGradGuard noGrad;

			// from_blob aliases the reused buffers rather than copying, so on
			// CPU this stays allocation-free. On GPU the .to() is the copy --
			// about 200KB per step for a 1v1 batch of ~50, against the ~3ms of
			// serial CPU forward it replaces.
			auto tQ =
				torch::from_blob(qBuf.data(), {b, 1, Q_SIZE}, torch::kFloat32);
			auto tKV = torch::from_blob(kvBuf.data(), {b, n, FEATURES},
										torch::kFloat32);
			auto tMask =
				torch::from_blob(maskBuf.data(), {b, n}, torch::kFloat32);

			if (onGPU) {
				tQ = tQ.to(module->device);
				tKV = tKV.to(module->device);
				tMask = tMask.to(module->device);
			}

			std::vector<c10::IValue> tup{tQ, tKV, tMask};
			out = module->mod.forward({c10::ivalue::Tuple::create(tup)});
		}

		// Both families return (heads, attention weights).
		const auto outer = out.toTuple()->elements();
		if (outer.empty())
			throw std::runtime_error("NectoPolicy: model returned an empty tuple");

		if (family == NectoFamily::Nexto) {
			// One [batch, 90] tensor of logits over whole control sets. view()
			// rather than a shape assertion because the trace already squeezed
			// the player axis out; this survives it coming back.
			torch::Tensor logits =
				outer[0].toTensor().to(torch::kCPU).contiguous().view({b, -1});

			const int count = static_cast<int>(logits.size(1));
			if (count != static_cast<int>(lookupTable.size()))
				throw std::runtime_error(
					"NectoPolicy: model emits " + std::to_string(count) +
					" actions, lookup table has " +
					std::to_string(lookupTable.size()));

			const float *data = logits.data_ptr<float>();
			for (int j = 0; j < b; j++)
				outActions[idxs[j]] = SampleLookupAction(
					data + static_cast<size_t>(j) * count, count);
			continue;
		}

		// Necto: a tuple of five tensors shaped [batch, 1, k].
		std::vector<torch::Tensor> heads;
		if (outer[0].isTuple()) {
			for (const auto &e : outer[0].toTuple()->elements())
				heads.push_back(e.toTensor());
		} else if (outer[0].isTensorList()) {
			for (const auto &t : outer[0].toTensorList())
				heads.push_back(torch::Tensor(t));
		} else {
			throw std::runtime_error("NectoPolicy: unexpected head container '" +
									 std::string(outer[0].tagKind()) + "'");
		}

		if (static_cast<int>(heads.size()) != NUM_HEADS)
			throw std::runtime_error("NectoPolicy: expected " +
									 std::to_string(NUM_HEADS) + " heads, got " +
									 std::to_string(heads.size()));

		// SampleAction reads these through data_ptr, so they have to be host
		// memory. A no-op when the model is already on the CPU. The logits are
		// tiny -- five heads of at most 3 values per car -- so this is a handful
		// of bytes back across the bus, not a real transfer.
		for (torch::Tensor &head : heads)
			head = head.to(torch::kCPU).contiguous();

		const float *headPtrs[NUM_HEADS];
		int headSizes[NUM_HEADS];
		for (int h = 0; h < NUM_HEADS; h++) {
			headSizes[h] = static_cast<int>(heads[h].size(-1));
			if (headSizes[h] > MAX_HEAD_SIZE)
				throw std::runtime_error("NectoPolicy: head wider than expected");
		}

		for (int j = 0; j < b; j++) {
			for (int h = 0; h < NUM_HEADS; h++)
				headPtrs[h] = heads[h].data_ptr<float>() +
							  static_cast<size_t>(j) * headSizes[h];
			outActions[idxs[j]] = SampleAction(headPtrs, headSizes);
		}
	}
}

