// necto_obs.py `_norm`. Note positions are divided by 2300 as well as
// velocities -- that is Necto's convention, not a transcription slip.
constexpr float NORM[NectoPolicy::FEATURES] = {
	1, 1, 1, 1, 1,          // 0-4   type flags
	2300, 2300, 2300,       // 5-7   position
	2300, 2300, 2300,       // 8-10  linear velocity
	1, 1, 1,                // 11-13 forward
	1, 1, 1,                // 14-16 up
	5.5f, 5.5f, 5.5f,       // 17-19 angular velocity
	1, 1, 1, 1              // 20-23 boost, timer, on ground, has flip
};

// necto_obs.py `_invert`: negate x and y of every vector triple, keep z.
constexpr float INVERT[NectoPolicy::FEATURES] = {
	1,  1,  1, 1, 1, //
	-1, -1, 1,       // position
	-1, -1, 1,       // linear velocity
	-1, -1, 1,       // forward
	-1, -1, 1,       // up
	-1, -1, 1,       // angular velocity
	1,  1,  1, 1     //
};

constexpr int NUM_HEADS = 5;
constexpr int MAX_HEAD_SIZE = 3;

// Column layout, shared by both families. Named because the Nexto relative pass
// walks it by stride rather than by triple.
constexpr int COL_POS = 5;      // 5-7
constexpr int COL_LIN_VEL = 8;  // 8-10
constexpr int COL_FORWARD = 11; // 11-13
constexpr int COL_ANG_VEL = 17; // 17-19
constexpr int COL_TIMER = 21;   // demo respawn / pad cooldown, or the raw flags

// Nexto's action space, transcribed from nexto/agent.py `make_lookup_table`.
//
// This is deliberately NOT RLGC::DefaultAction's table, even though the two are
// currently generated by identical loops in identical order and agree entry for
// entry. That agreement is a fact about our action parser, which is ours to
// change -- there is already one local patch in it -- whereas this table is part
// of Nexto's trained weights and is not. Sharing them would turn a future tweak
// to our own action set into a silent corruption of the opponent.
std::vector<Action> BuildNextoLookupTable() {
	constexpr float R_B[] = {0, 1};
	constexpr float R_F[] = {-1, 0, 1};

	std::vector<Action> actions;

	// Ground
	for (float throttle : R_F)
		for (float steer : R_F)
			for (float boost : R_B)
				for (float handbrake : R_B) {
					if (boost == 1 && throttle != 1)
						continue;
					actions.push_back({throttle, steer, 0, steer, 0, 0, boost,
									   handbrake});
				}

	// Aerial
	for (float pitch : R_F)
		for (float yaw : R_F)
			for (float roll : R_F)
				for (float jump : R_B)
					for (float boost : R_B) {
						if (jump == 1 && yaw != 0) // only need roll for sideflip
							continue;
						if (pitch == 0 && roll == 0 && jump == 0) // ground dupe
							continue;
						const float handbrake =
							(jump == 1 && (pitch != 0 || yaw != 0 || roll != 0))
								? 1.f
								: 0.f;
						actions.push_back({boost, yaw, pitch, yaw, roll, jump,
										   boost, handbrake});
					}

	return actions;
}

// Reads the family off the traced forward's return type.
//
// Necto returns ((h0, h1, h2, h3, h4), (weights,)); Nexto returns
// (logits, (weights, weights)). So the first element of the returned tuple is a
// tuple for one and a bare tensor for the other -- a structural difference, not
// a guess from the filename.
NectoFamily DetectFamily(torch::jit::script::Module &mod) {
	const c10::FunctionSchema &schema =
		mod.get_method("forward").function().getSchema();
	if (schema.returns().size() != 1)
		throw std::runtime_error("forward() does not return a single value");

	const auto tuple = schema.returns()[0].type()->cast<c10::TupleType>();
	if (!tuple || tuple->elements().empty())
		throw std::runtime_error("forward() does not return a tuple");

	const c10::TypePtr &head = tuple->elements()[0];
	if (head->cast<c10::TupleType>())
		return NectoFamily::Necto;
	if (head->cast<c10::TensorType>())
		return NectoFamily::Nexto;

	throw std::runtime_error("unrecognised head type '" + head->str() + "'");
}

// Rewrites every baked-in device constant in a loaded module to `dev`.
//
// Nexto's ControlsPredictorDot embeds its action lookup table and dots it
// against the player embedding, and the trace froze the table's `.to(device)`
// as `.to(device=cpu)` because Rolv traced on CPU:
//
//     input = torch.to(CONSTANTS.c2, dtype=6, layout=0, device=torch.device("cpu"))
//     res = torch.einsum("ad,bpd->bpa", [(net).forward(input), player_emb])
//
// torch::jit::load(path, kCUDA) moves the weights but not that node, so the
// einsum gets a CPU table against CUDA weights and throws "Expected all tensors
// to be on the same device". Necto has no such node, which is why this only
// showed up on the Nexto model.
//
// Rewriting the constant is the honest fix: the alternative is running the whole
// opponent on the CPU, and this forward is serial on the collection thread with
// every arena worker parked, so that cost lands on every env step. Loading is
// lazy about building execution plans, so editing the graph here is safe.
//
// Returns how many constants were changed, so the caller can say so out loud
// rather than silently depending on a graph detail of someone else's export.
int RetargetDeviceConstants(torch::jit::Block *block, torch::Device dev) {
	int changed = 0;

	for (auto it = block->nodes().begin(); it != block->nodes().end();) {
		torch::jit::Node *node = *it;
		++it; // the node may be destroyed below

		for (torch::jit::Block *sub : node->blocks())
			changed += RetargetDeviceConstants(sub, dev);

		if (node->kind() != torch::jit::prim::Constant ||
			node->outputs().size() != 1)
			continue;

		torch::jit::Value *out = node->output();
		const auto value = torch::jit::toIValue(out);
		if (!value || !value->isDevice() || value->toDevice() == dev)
			continue;

		torch::jit::WithInsertPoint guard(node);
		torch::jit::Value *repl =
			block->owningGraph()->insertConstant(c10::IValue(dev));
		out->replaceAllUsesWith(repl);
		node->destroy();
		changed++;
	}

	return changed;
}

int RetargetDeviceConstants(torch::jit::script::Module &mod,
							torch::Device dev) {
	int changed = 0;
	for (auto sub : mod.modules())
		for (auto &method : sub.get_methods())
			changed += RetargetDeviceConstants(method.graph()->block(), dev);
	return changed;
}

